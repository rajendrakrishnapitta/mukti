function pv(
  video: Omit<PhilosophyVideo, "languages">,
): PhilosophyVideo {
  return { ...video, languages: EN };
}

function asTe(
  video: Omit<PhilosophyVideo, "languages">,
): PhilosophyVideo {
  return { ...video, languages: TE };
}

function asKFoundation(
  video: Omit<PhilosophyVideo, "channel" | "channelUrl" | "languages">,
): PhilosophyVideo {
  return pv({
    ...video,
    channel: K_FOUNDATION_YOUTUBE.channel,
    channelUrl: K_FOUNDATION_YOUTUBE.url,
    philosopherIds: ["krishnamurti", ...(video.philosopherIds ?? [])],
  });
}

